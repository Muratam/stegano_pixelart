    <div class="prose">
      <p>
        ドット絵に文字列をこっそり埋め込む（ステガノグラフィー）ツールです。
        <a href="https://www.ieice.org/ken/paper/20200305e1wB/">修士課程の研究</a>のプログラム（Nim）を TypeScript に移し、ブラウザだけで動くようにしました。画像はサーバーに送りません。
      </p>

      <h3>しくみ</h3>
      <ul>
        <li>二値画像のステガノグラフィーと同じように、ドット絵の<strong>同じ色の領域の境界</strong>に情報を持たせます。色を新しく作らず、隣の画素の色に塗り替えるだけなので、自然な見た目のまま埋め込めます。</li>
        <li>市松模様の片方の画素が 1 ビットずつ持ちます。値は「その画素の色が、上下左右でいちばん多い色（代表色）と同じか」で決まります。上下左右の画素は変えないので、取り出すときも同じ画素を読めます。</li>
        <li>画素を変えるコストは、周りの模様の変化（crmiLTP というパターンのヒストグラムの差）と、色の違い（CIEDE2000 の色差）の積です。</li>
        <li>STC（Syndrome-Trellis Codes）で、コストの合計が小さくなる変え方を選びます。1 ビットあたり 0.5 画素より少ない変更で済みます。</li>
        <li>鍵は、どの画素がどのビットを持つかの並べ替えに使う乱数のシードです。<strong>暗号化はしていません</strong>。秘密にしたい内容は先に暗号化してください。</li>
      </ul>

      <h3>使い方の注意</h3>
      <ul>
        <li>画素の値が 1 つでも変わると取り出せません。PNG のまま渡してください（JPEG・縮小・拡大・SNS の再圧縮で壊れます）。</li>
        <li>入る量は小さいです（40×64 のサンプルで 15 バイト程度）。色の少ない、境界の多いドット絵ほど多く入ります。</li>
        <li>外側 2px と、上下左右がすべて同じ色の画素は使いません。透過の PNG は RGB だけを見ます（アルファは保ちます）。</li>
      </ul>

      <h3>元のプログラムとの違い</h3>
      <ul>
        <li>埋め込む中身は、元のプログラムではビットの列そのものでした。Web 版は文字列（UTF-8）に長さと CRC-16 を付けて埋め込み、取り出すときに長さを知らなくても戻せるようにしています。</li>
        <li>鍵（元は 1234 で固定）・STC の h（元は 10）・変えない色（元はサンプル用に 1 色）を選べるようにしました。鍵 1234・h 10 で同じビットの列を埋め込むと、元のプログラムと同じ画像になります（テストで照合しています）。</li>
      </ul>

