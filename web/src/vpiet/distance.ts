/** vpiet の rgb2xyz・xyz2lab（立方根は pow(x, 1/3)。ドット絵ステガノの方は cbrt） */
function lab(rgb: number): [number, number, number] {
  const lin = (v: number) => {
    const nx = v / 255;
    return nx > 0.04045 ? Math.pow((nx + 0.055) / 1.055, 2.4) : nx / 12.92;
  };
  const lr = lin((rgb >> 16) & 0xff);
  const lg = lin((rgb >> 8) & 0xff);
  const lb = lin(rgb & 0xff);
  const x = lr * 0.4124 + lg * 0.3576 + lb * 0.1805;
  const y = lr * 0.2126 + lg * 0.7152 + lb * 0.0722;
  const z = lr * 0.0193 + lg * 0.1192 + lb * 0.9505;
  const f = (v: number) => (v > 0.008856 ? Math.pow(v, 1.0 / 3.0) : 7.787 * v + 0.1379);
  const nx = f(x / 0.95047);
  const ny = f(y / 1.0);
  const nz = f(z / 1.08883);
  return [116 * ny - 16, 500 * (nx - ny), 200 * (ny - nz)];
}
const PIET_LAB = Array.from({ length: MAX_COLOR + 1 }, (_, c) => lab(pietRgb(c)));
const nearestCache = new Map<number, PietColor>();

/** RGB → いちばん近い Piet の色（vpiet の toNearlestPietColor。色差は整数に切り捨てて比べ、同じなら番号の小さい方） */
export function toNearestPietColor(rgb: number): PietColor {
  const hit = nearestCache.get(rgb);
  if (hit !== undefined) return hit;
  const [l1, a1, b1] = lab(rgb);
  let best = 0;
  let min = 1e12;
  for (let c = 0; c <= MAX_COLOR; c++) {
    const [l2, a2, b2] = PIET_LAB[c];
    const d = Math.trunc(ciede2000(l1, a1, b1, l2, a2, b2));
    if (min > d) {
      min = d;
      best = c;
    }
  }
  nearestCache.set(rgb, best);
  return best;
}
